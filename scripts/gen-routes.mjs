// Generates lib/api/routes.gen.ts: the proxy allowlist of (method, path) pairs taken from
// contract/openapi.yaml. Run by `npm run gen:api`; CI fails if it is out of date.
import { readFileSync, writeFileSync } from "node:fs";

const spec = readFileSync("contract/openapi.yaml", "utf8").split(/\r?\n/);
const methods = new Set(["get", "post", "put", "patch", "delete"]);
const routes = [];
let inPaths = false;
let current = null;

for (const line of spec) {
  if (/^paths:\s*$/.test(line)) {
    inPaths = true;
    continue;
  }
  if (inPaths && /^\S/.test(line)) break; // next top-level key ends the paths block
  if (!inPaths) continue;
  const path = line.match(/^ {2}(\/[^:]*):\s*$/);
  if (path) {
    current = path[1];
    continue;
  }
  const method = line.match(/^ {4}([a-z]+):\s*$/);
  if (current && method && methods.has(method[1]))
    routes.push([method[1].toUpperCase(), current]);
}

if (routes.length === 0) {
  console.error("No routes found in contract/openapi.yaml");
  process.exit(1);
}

const body = routes.map(([m, p]) => `  ["${m}", "${p}"],`).join("\n");
writeFileSync(
  "lib/api/routes.gen.ts",
  `// Generated by scripts/gen-routes.mjs from contract/openapi.yaml. Do not edit.\nexport const CONTRACT_ROUTES: ReadonlyArray<readonly [string, string]> = [\n${body}\n];\n`,
);
console.log(`Wrote ${routes.length} routes to lib/api/routes.gen.ts`);
